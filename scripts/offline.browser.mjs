import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
import nextEnv from "@next/env";
import { getDatabase } from "../src/server/db.ts";
import { provisionCompany } from "../src/server/provisioning.ts";
import { publishBuiltInTemplates } from "../src/server/templates/service.ts";

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
nextEnv.loadEnvConfig(process.cwd(), true, { info() {}, error() {} });
const { client, db, config } = getDatabase();
assert.match(config.databaseName, /_(dev|test)$/);
assert.equal(config.baseURL, process.env.AUTH_TEST_BASE_URL);
assert.ok(["localhost", "127.0.0.1"].includes(new URL(config.baseURL).hostname));
const company = `Offline QA ${randomUUID()}`;
const email = `offline.${randomUUID()}@example.invalid`;
const password = randomBytes(24).toString("base64url");
let fixture, browser, page;
const errors = [];
const failedRequests = [];
try {
  fixture = await provisionCompany(client, db, config, { company, name: "Offline QA", email, password });
  await publishBuiltInTemplates(client, db, fixture.organizationId, fixture.userId);
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: "allow" });
  page = await context.newPage();
  const setup = (p) => { p.setDefaultTimeout(20000); p.on("dialog", (dialog) => dialog.accept()); p.on("pageerror", (error) => errors.push(error.message)); p.on("requestfailed", (request) => failedRequests.push(new URL(request.url()).pathname)); };
  setup(page);
  await page.goto(`${config.baseURL}/logga-in`);
  await page.getByLabel("E-postadress").fill(email);
  await page.getByLabel("Lösenord").fill(password);
  await page.getByRole("button", { name: "Logga in", exact: true }).click();
  await page.getByRole("button", { name: new RegExp(company) }).click();
  await page.waitForURL("**/admin/fakturaunderlag");
  await page.goto(`${config.baseURL}/rapportor/ny/tma`);
  await page.getByRole("button", { name: "Aktivera offline på den här enheten" }).click();
  await page.getByText("Sparat på den här enheten – inte skickat till servern.", { exact: true }).waitFor();
  await page.evaluate(() => navigator.serviceWorker.ready);
  const fill = async (values) => { for (const [key, value] of Object.entries(values)) await page.locator(`[name="${key}"]`).fill(value); };
  await fill({ kund: "Offline kund", tmaRegnr: "abc123", datum: "2026-10-22", vagnummer: "Testväg", arbetsplats: "Testplats", starttid: "22:30", sluttid: "00:30", rast: "30", arbetsuppgifter: "Skydd vid vägarbete", namn: "Offline QA" });
  await page.locator('[name="kontrollFore"][value="ja"]').check();
  await page.locator('[name="tillbud"][value="nej"]').check();
  const readDrafts = () => page.evaluate(() => Object.keys(localStorage).filter((key) => key.includes(".draft.")).map((key) => JSON.parse(localStorage.getItem(key))));
  await page.waitForFunction(() => Object.keys(localStorage).some((key) => key.includes(".draft.") && JSON.parse(localStorage.getItem(key)).answers.tillbud === "nej"));
  const [first] = await readDrafts();
  assert.equal(first.answers.debiterbaraTimmar, "1,5");
  await context.setOffline(true);
  await page.getByRole("button", { name: "Spara utkast", exact: true }).click();
  await page.getByText(/Ingen anslutning. Rapporten har inte skickats/).waitFor();
  assert.equal(await db.collection("reports").countDocuments({ organizationId: fixture.organizationId }), 0);
  await page.reload();
  await page.waitForURL("**/offline");
  await page.getByRole("button", { name: "Öppna utkast", exact: true }).click();
  assert.equal(await page.locator('[name="kund"]').inputValue(), "Offline kund");
  assert.equal(await page.locator('[name="debiterbaraTimmar"]').inputValue(), "1,5");
  await page.locator('[name="debiterbaraTimmar"]').fill("3");
  await page.waitForFunction(() => Object.keys(localStorage).some((key) => key.includes(".draft.") && JSON.parse(localStorage.getItem(key)).answers.debiterbaraTimmar === "3"));
  await page.close();
  page = await context.newPage(); setup(page);
  await page.goto(`${config.baseURL}/offline`);
  await page.getByRole("button", { name: "Öppna utkast", exact: true }).click();
  assert.equal(await page.locator('[name="debiterbaraTimmar"]').inputValue(), "3");
  assert.deepEqual((await readDrafts())[0].automaticTimeFields, []);
  console.log("PASS: offline reload and closing/reopening a tab preserve answers, automatic/manual time mode and stable ID");
  const stale = await context.newPage(); setup(stale);
  await stale.goto(`${config.baseURL}/offline`);
  await stale.getByRole("button", { name: "Öppna utkast", exact: true }).click();
  await stale.locator('[name="kund"]').waitFor();
  await page.reload();
  await page.getByRole("button", { name: "Öppna utkast", exact: true }).click();
  await page.locator('[name="arbetsuppgifter"]').fill("Senaste lokala arbete");
  await page.waitForFunction(() => Object.keys(localStorage).some((key) => key.includes(".draft.") && JSON.parse(localStorage.getItem(key)).answers.arbetsuppgifter === "Senaste lokala arbete"));
  await stale.locator('[name="arbetsuppgifter"]').fill("Äldre flik får inte skriva över");
  await stale.getByText(/Kunde inte spara lokalt.*annan flik/).waitFor();
  assert.equal((await readDrafts())[0].answers.arbetsuppgifter, "Senaste lokala arbete");
  await stale.close();
  console.log("PASS: stale tab cannot overwrite newer local work");
  await mkdir(".next/qa", { recursive: true });
  await page.screenshot({ path: ".next/qa/offline-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);

  await context.setOffline(false);
  await page.getByRole("button", { name: "Skicka in", exact: true }).click();
  await page.getByRole("button", { name: "Bekräfta och skicka in", exact: true }).click();
  await page.waitForURL("**/rapportor/rapporter/**?sparad=1");
  assert.equal(await db.collection("reports").countDocuments({ _id: first.id, organizationId: fixture.organizationId }), 1);
  assert.equal(await db.collection("reportVersions").countDocuments({ reportId: first.id, organizationId: fixture.organizationId }), 1);
  assert.equal((await readDrafts()).length, 0);
  console.log("PASS: reconnect and explicit submit create one report/version and remove only the confirmed local copy");

  await page.goto(`${config.baseURL}/offline`);
  await context.setOffline(true);
  await page.getByRole("button", { name: `${company} · Underlag TMA`, exact: true }).click();
  await page.locator('[name="kund"]').fill("Ny från sparad mall");
  await page.waitForFunction(() => Object.keys(localStorage).some((key) => key.includes(".draft.") && JSON.parse(localStorage.getItem(key)).answers.kund === "Ny från sparad mall"));
  assert.notEqual((await readDrafts())[0].id, first.id);
  await context.setOffline(false);
  // The server succeeds, but the response is lost. Reload and retry must use the same ID.
  const [pending] = await readDrafts();
  await page.route("**/api/foretag/*/rapporter", async (route) => { await route.fetch(); await route.abort("failed"); });
  await page.getByRole("button", { name: "Spara utkast", exact: true }).click();
  await page.getByText(/Kunde inte bekräfta sparandet/).waitFor();
  assert.equal(await db.collection("reports").countDocuments({ _id: pending.id }), 1);
  await page.unroute("**/api/foretag/*/rapporter");
  await page.reload();
  await page.getByRole("button", { name: "Öppna utkast", exact: true }).click();
  await page.getByRole("button", { name: "Spara utkast", exact: true }).click();
  await page.getByText(/Utkastet finns redan sparat/).waitFor();
  assert.equal(await db.collection("reports").countDocuments({ _id: pending.id }), 1);
  await page.getByRole("button", { name: "Öppna den sparade rapporten", exact: true }).click();
  await page.waitForURL(`**/rapportor/rapporter/${pending.id}`);
  console.log("PASS: lost server response survives reload; retry never duplicates the report");
  // Save once normally so the following revision-conflict check starts from a confirmed page.
  await page.getByRole("button", { name: "Spara utkast", exact: true }).click();
  await page.waitForURL("**/rapportor/rapporter/**?sparad=1");
  const secondId = new URL(page.url()).pathname.split("/").pop();
  await page.locator('[name="kund"]').fill("Lokal komplettering av utkast");
  await page.waitForFunction(() => Object.keys(localStorage).some((key) => key.includes(".draft.") && JSON.parse(localStorage.getItem(key)).answers.kund === "Lokal komplettering av utkast"));
  await db.collection("reports").updateOne({ _id: secondId, organizationId: fixture.organizationId }, { $inc: { revision: 1 }, $set: { "answers.kund": "Nyare på servern" } });
  await page.getByRole("button", { name: "Spara utkast", exact: true }).click();
  await page.getByText(/Rapporten har ändrats eller fått ett nytt beslut/).waitFor();
  assert.equal((await readDrafts())[0].answers.kund, "Lokal komplettering av utkast");
  assert.equal((await db.collection("reports").findOne({ _id: secondId })).answers.kund, "Nyare på servern");
  console.log("PASS: new report from saved template works offline; stale server revision cannot overwrite newer data");

  await page.goto(`${config.baseURL}/offline`);
  await page.getByRole("button", { name: "Öppna utkast", exact: true }).click();
  await db.collection("session").deleteMany({ userId: fixture.userId });
  await page.getByRole("button", { name: "Spara utkast", exact: true }).click();
  await page.getByText(/Logga in med kontot som skapade utkastet/).waitFor();
  assert.equal((await readDrafts()).length, 1);
  console.log("PASS: expired session preserves local data and requires login before syncing");
  await page.goto(`${config.baseURL}/logga-in`);
  await page.getByLabel("E-postadress").fill(email);
  await page.getByLabel("Lösenord").fill(password);
  await page.getByRole("button", { name: "Logga in", exact: true }).click();
  await page.getByRole("button", { name: new RegExp(company) }).click();
  await page.waitForURL("**/admin/fakturaunderlag");
  const otherTab = await context.newPage(); setup(otherTab);
  await otherTab.goto(`${config.baseURL}/offline`);
  await otherTab.getByRole("button", { name: "Öppna utkast", exact: true }).click();
  await otherTab.locator('[name="kund"]').waitFor();
  await page.getByRole("button", { name: "Logga ut", exact: true }).click();
  await page.waitForURL("**/logga-in");
  assert.equal(await page.evaluate(() => Object.keys(localStorage).filter((key) => key.startsWith("arbetsrapporter.offline.")).length), 0);
  await otherTab.locator('[name="kund"]').waitFor({ state: "detached" });
  await otherTab.close();
  const cachedURLs = await page.evaluate(async () => { const result = []; for (const key of await caches.keys()) { for (const request of await (await caches.open(key)).keys()) result.push(new URL(request.url).pathname); } return result; });
  assert.ok(cachedURLs.every((path) => path === "/offline" || path.startsWith("/_next/static/")));
  assert.deepEqual(errors, []);
  console.log("PASS: confirmed logout removes local data; no private HTML/API responses cached; no browser runtime errors");
} catch (error) {
  if (page && !page.isClosed()) {
    await mkdir(".next/qa", { recursive: true });
    await page.screenshot({ path: ".next/qa/offline-failure.png", fullPage: true }).catch(() => {});
  }
  console.error("Browser runtime errors:", errors);
  console.error("Failed request paths:", failedRequests);
  if (page && !page.isClosed()) console.error("Local storage key count:", await page.evaluate(() => localStorage.length));
  throw error;
} finally {
  if (browser) await browser.close();
  if (fixture) {
    for (const collection of ["reportEvents", "reportVersions", "reports", "templateVersions", "templates", "memberships", "organizationEvents"]) await db.collection(collection).deleteMany({ organizationId: fixture.organizationId });
    await db.collection("organizations").deleteOne({ _id: fixture.organizationId });
    for (const collection of ["session", "account"]) await db.collection(collection).deleteMany({ userId: fixture.userId });
    await db.collection("user").deleteOne({ _id: fixture.userId });
  }
  await client.close();
}
